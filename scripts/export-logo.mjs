// Exports the logo system (app icon, favicon, lockup, wordmark, mascot) from the concept preview
// into standalone SVG files in assets/brand. Source of truth for the art: design/concepts/logo-preview.html
// Usage: node scripts/export-logo.mjs  — then node scripts/export-pwa-icons.mjs for the PNG/ICO icons.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "assets/brand");
const html = readFileSync(join(root, "design/concepts/logo-preview.html"), "utf8");
const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];

// Minimal DOM stub: the preview script only assigns innerHTML on elements by id.
const elements = {};
const document = { getElementById: (id) => (elements[id] ??= { innerHTML: "" }) };
const ctx = vm.createContext({ document, Math });
vm.runInContext(`${script}\n;globalThis.__x = { lockup, icon, wordmarkRow, mascot };`, ctx);
const { lockup, icon, wordmarkRow, mascot } = ctx.__x;

const SOURCE =
  "Generated by scripts/export-logo.mjs from design/concepts/logo-preview.html; edit the preview, not this file.";
const FONT = `<style>@import url('https://fonts.googleapis.com/css2?family=Baloo+2:wght@800');</style>`;

function standalone(svg, note, { withFont = false } = {}) {
  let s = svg
    .trim()
    .replace(/^<svg/, '<svg xmlns="http://www.w3.org/2000/svg"')
    .replace(/ class="[^"]*"/, "")
    .replace(/\n\s*\n/g, "\n");
  if (withFont) s = s.replace(/^(<svg[^>]*>)/, `$1${FONT}`);
  return `<!-- Chibi Bluff ${note}\n     ${SOURCE} -->\n${s}\n`;
}

function write(name, content) {
  writeFileSync(join(out, name), content);
  console.log("wrote", `assets/brand/${name}`);
}

// Icons: no text, safe to use anywhere (docs/architecture.md §6.1).
write(
  "app-icon.svg",
  standalone(
    icon(),
    "app icon: the masked chibi in front of a fan of cards. Head and mask stay inside the 80% safe zone of the maskable icon; the body bleeds off the bottom.",
  ),
);
write(
  "favicon.svg",
  standalone(
    icon({ simple: true }),
    "favicon: the app icon simplified for 16–48px (no rays, no sparkles, bigger bust, corners rounded in the file).",
  ),
);
write(
  "logo-mascot.svg",
  standalone(mascot(), "mascot only (bust, no text): for the app to compose with its own text."),
);

// Text is live Baloo 2 loaded from Google Fonts: fine in browsers, convert to paths for print or stores.
const text = { withFont: true };
write(
  "logo-lockup.svg",
  standalone(
    lockup({ label: "" }),
    "lockup without the theme ribbon. Text is live Baloo 2 (Google Fonts).",
    text,
  ),
);
write(
  "logo-lockup.vi.svg",
  standalone(
    lockup(),
    "lockup with the Giang Hồ Nhí Nhố ribbon (Vietnamese). Text is live Baloo 2 (Google Fonts).",
    text,
  ),
);
write(
  "logo-lockup.en.svg",
  standalone(
    lockup({ label: "WACKY WUXIA" }),
    "lockup with the Wacky Wuxia ribbon (English). Text is live Baloo 2 (Google Fonts).",
    text,
  ),
);
write(
  "logo-wordmark.svg",
  standalone(
    wordmarkRow(),
    "horizontal wordmark for headers: small mascot + name on one line. Text is live Baloo 2 (Google Fonts).",
    text,
  ),
);
